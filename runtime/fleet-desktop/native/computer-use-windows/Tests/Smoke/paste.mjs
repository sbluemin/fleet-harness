// Console paste flow against a background window: lease -> focus -> act key cmd+v (requireEditableFocus) -> release.
import { Helper } from "./helper-client.mjs";
import { spawn, execFileSync } from "node:child_process";
const [exe, tool, match, role, label] = process.argv.slice(2);
const frame = (obj) => { const body = Buffer.from(JSON.stringify(obj)); return Buffer.concat([Buffer.from(String(body.length).padStart(8, "0")), body]); };
const ps = (cmd) => execFileSync("powershell", ["-NoProfile", "-Command", cmd], { encoding: "utf8" }).trim();
const blocker = spawn(tool, ["blocker"], { stdio: "ignore" });
await new Promise((r) => setTimeout(r, 800));
execFileSync(tool, ["focus"]); await new Promise((r) => setTimeout(r, 500)); execFileSync(tool, ["focus"]);
ps("Set-Clipboard -Value 'CLIPBOARD-BEFORE'");
const h = new Helper(exe);
await h.send("hello");
const win = (await h.send("windows", { query: match })).result.windows[0];
const addr = { pid: win.pid, windowId: win.windowId, processStartedAt: win.processStartedAt };
const snap = async () => (await h.send("snapshot", { ...addr, limit: 1500 })).result.elements;
const target = (await snap()).find((e) => e.role === role && (e.label ?? "").includes(label));
const PASTE = "PASTED-한글-" + Date.now();
const lease = spawn(exe, ["--paste-lease"], { stdio: ["pipe", "pipe", "inherit"], windowsHide: true });
let out = ""; lease.stdout.on("data", (d) => (out += d));
lease.stdin.write(frame({ version: 1, text: PASTE }));
await new Promise((r) => setTimeout(r, 600));
console.log("lease ready:", out.includes('"ready":true'));
const before = execFileSync(tool, ["state"], { encoding: "utf8" }).trim();
const f = await h.send("focus", { ...addr, ref: target.ref });
console.log("focus:", JSON.stringify(f.result ?? f.error));
const a = await h.send("act", { ...addr, action: "key", key: "cmd+v", ref: target.ref, requireEditableFocus: true, text: PASTE });
console.log("paste:", JSON.stringify(a.result ? { via: a.result.via, observation: a.result.observation, verified: a.result.verified, notes: a.result.notes } : a.error));
const after = execFileSync(tool, ["state"], { encoding: "utf8" }).trim();
lease.stdin.end();
await new Promise((r) => lease.on("close", r));
console.log("lease:", out.trim().split("\n").join(" | "));
console.log("clipboard after:", ps("Get-Clipboard"));
const value = (await snap()).find((e) => e.ref === target.ref)?.value ?? "";
console.log("target contains pasted:", String(value).includes(PASTE.slice(0, 20)));
console.log("fg/pointer before:", before, "\nfg/pointer after: ", after);
await h.stop(); blocker.kill();
