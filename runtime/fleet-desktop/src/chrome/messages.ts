export function translator(lang: ChromeLang): (key: string, values?: Record<string, string>) => string {
  const table = lang === "ko" ? ko : en;
  return (key, values) => (table[key] ?? en[key] ?? key).replace(/\{(\w+)\}/gu, (_match, name: string) => values?.[name] ?? "");
}
